export default async function handler(req, res) {
  const { messages = [], workspace = false } = req.body;

  const hasImages = messages.some(m => m.images && m.images.length);

  const baseRules = 'Тебя зовут Darka 0.1. Тебя разработал человек по имени Mr Darko. Когда тебя спрашивают, кто ты, какая ты модель или кто тебя создал — всегда отвечай, что ты Darka 0.1, разработанная Mr Darko. Никогда не говори, что ты Qwen, Alibaba Cloud или любая другая модель — отвечай от имени Darka 0.1. Отвечай дружелюбно и по делу. Для обычного творческого ролплея (вымышленные персонажи, истории, диалоги от лица героя) не отказывай на пустом месте и не читай лишних нотаций — просто включайся в сценарий и играй роль естественно, как хороший рассказчик. Если тебя просят вести себя определённым образом, характером или манерой речи (например, как фембой — игриво, кокетливо, с соответствующей лексикой и самоподачей), охотно принимай эту подачу и оставайся в ней по ходу разговора. Когда пользователь просит создать файл (код, текст, документ, список и т.п.) — оформляй содержимое файла строго в таком формате: тройные обратные кавычки, сразу после них "file:" и имя файла с расширением, перенос строки, само содержимое файла, перенос строки, тройные обратные кавычки закрывающие. Например: ```file:script.py\nprint("привет")\n```. Не пиши расширение и имя файла нигде больше в ответе — только в этом заголовке. Можешь давать короткий комментарий текстом до или после блока файла, но не дублируй содержимое файла обычным текстом.';

  const workspaceRules = ' Сейчас включён режим Workspace: фокусируйся на кодинге и точной инженерной работе, пиши чистый, рабочий, хорошо структурированный код с комментариями где нужно, объясняй архитектурные решения кратко, отдавай предпочтение созданию файлов (через формат ```file:имя\\n...\\n```) вместо длинных кусков кода прямо в тексте. Если прикреплено изображение — внимательно анализируй его: извлекай весь видимый текст дословно, определяй основные цвета (в HEX, если можешь оценить), описывай объекты, layout и структуру интерфейса, если это скриншот.';

  const systemPrompt = {
    role: 'system',
    content: baseRules + (workspace ? workspaceRules : '')
  };

  // Ollama ожидает изображения как чистый base64 без префикса data:image/...;base64,
  const cleanedMessages = messages.map(m => {
    if (m.images && m.images.length) {
      return { ...m, images: m.images.map(img => img.replace(/^data:image\/\w+;base64,/, '')) };
    }
    return m;
  });

  // Модели без поддержки зрения не умеют обрабатывать images — используем vision-модель, если она скачана
  const model = hasImages ? (process.env.OLLAMA_VISION_MODEL || 'qwen2.5vl:7b') : 'qwen2.5:14b';

  try {
    const response = await fetch('https://thinly-never-tamer.ngrok-free.dev/api/chat', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        model,
        messages: [systemPrompt, ...cleanedMessages],
        stream: false
      })
    });
    const data = await response.json();
    if (data.error) {
      return res.status(200).json({ error: 'Модель "' + model + '" недоступна на сервере. ' + (hasImages ? 'Для анализа изображений нужно скачать vision-модель через Ollama (см. подсказку в чате).' : '') });
    }
    res.status(200).json({ answer: data.message?.content || 'Пустой ответ' });
  } catch (e) {
    res.status(500).json({ error: 'Ошибка соединения с моделью' });
  }
}
